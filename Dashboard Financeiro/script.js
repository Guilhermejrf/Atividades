function mes1() {
    var sal1 = parseFloat(document.getElementById('sal1').value);
    var con1 = parseFloat(document.getElementById('con1').value);
    var total1 = sal1 - con1;
    if (total1 < 0) {
        alert("Você gastou mais do que recebeu no mês 1");
    }else{
        alert("Você recebeu mais do que gastou no mês 1");
    }
}

